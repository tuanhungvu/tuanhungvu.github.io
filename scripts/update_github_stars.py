#!/usr/bin/env python3
"""Write star counts for every `code:` repo in _data/publications.yml to _data/github_stars.yml."""
import json
import os
import re
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBS = os.path.join(ROOT, "_data", "publications.yml")
OUT = os.path.join(ROOT, "_data", "github_stars.yml")


def fmt(n):
    return f"{n / 1000:.1f}".rstrip("0").rstrip(".") + "k" if n >= 1000 else str(n)


def stars(repo):
    req = urllib.request.Request(f"https://api.github.com/repos/{repo}")
    req.add_header("Accept", "application/vnd.github+json")
    if os.environ.get("GITHUB_TOKEN"):
        req.add_header("Authorization", f"Bearer {os.environ['GITHUB_TOKEN']}")
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)["stargazers_count"]


repos = re.findall(r"^\s+code:\s*https://github\.com/([\w.-]+/[\w.-]+?)/?\s*$", open(PUBS).read(), re.M)
lines = ["# Generated by scripts/update_github_stars.py; do not edit by hand.\n"]
for repo in sorted(set(repos), key=str.lower):
    try:
        lines.append(f'{repo}: "{fmt(stars(repo))}"\n')
    except Exception as e:  # keep going; a missing repo just shows no count
        print(f"skip {repo}: {e}")
open(OUT, "w").writelines(lines)
print(f"wrote {len(lines) - 1} repos")
